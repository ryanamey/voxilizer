import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  /**
   * Cross-origin isolation. Required for SharedArrayBuffer, which the audio
   * engine will use to pass audio between the UI, worker and AudioWorklet
   * threads without copying. Set from day one: adding it later can break
   * third-party embeds. Any cross-origin resource must send CORP/CORS headers.
   */
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
          { key: "Cross-Origin-Embedder-Policy", value: "require-corp" },
        ],
      },
    ];
  },
};

export default nextConfig;
